    @staticmethod
    def project_is_active() -> bool:
        """
        Check if a saved project is currently open.
        """
        if QgsProject.instance().fileName() != '':
            return True
        else:
            QMessageBox.information(None, "Information", "Please open a saved project.")
            return False


    @staticmethod
    def check_layer_exists(layer_name: str) -> bool:
        """
        Check if a given layer name exists in the list of current layers.
        """
        if len(QgsProject.instance().mapLayersByName(layer_name)) > 0:
            return True
        else:
            return False


    @staticmethod
    def check_fdc_layers_exist() -> bool:
        """
        Check if the Field Data Capture layers exist in the current layers.
        """
        missing_layers = [
            table_name
            for table_name in TABLE_LIST
            if not FieldDataCapture.check_layer_exists(table_name)
        ]
        if len(missing_layers) == 0:
            return True
        else:
            return False


    def validate_qgis_state(
        self,
        project_active: bool = False,
        db_file_exists: bool = False,
        fdc_layers_exist: bool = False,
        layer_name_exists: Optional[str] = None,
    ) -> bool:
        """
        Validate that the given options are currently OK in QGIS.
        Returns a boolean indicating the validity of the current state of QGIS.
        """
        # If we need to check project_active and the project is not active
        if project_active and not self.project_is_active():
            return False

        # If we need to check the db_file_exists and the db file does not exist
        if db_file_exists and not self.db_file.exists():
            QMessageBox.information(None, "Information", f"Could not find file:\n\n{self.db_file}")
            return False

        # If we need to check the fdc_layers_exist and the fdc layers do not exist
        if fdc_layers_exist and not self.check_fdc_layers_exist():
            QMessageBox.information(None, "Information", "Could not find the required layers for Field Data Capture.")
            return False

        # If we need to check that a given layer_name_exists and the given layer name does not exist
        if layer_name_exists is not None and not self.check_layer_exists(layer_name_exists):
            QMessageBox.information(None, "Information", f"Could not find layer: {layer_name_exists}")
            return False

        return True


    def run_function_list(self, functions: list[Callable]) -> bool:
        """
        Run all the given functions in order.
        Each function must return a boolean indicating it's success.
        If a function returns False, function execution will end.
        Returns a boolean indicating success of the process.
        """
        for function_ in functions:
            return_ = function_()
            # We don't want to continue through the setup if a process fails
            if return_ is False:
                return False

        return True


    def add_gpkg_to_project(self) -> bool:
        """
        Add the GeoPackage file to the current project.
        Returns a boolean indicating success of the process.
        """
        if not self.validate_qgis_state(project_active=True):
            return False

        if self.db_file.exists():
            result = QMessageBox.question(
                None, "File Already Exists",
                f"The file already exists, would you like to overwrite the file?\n\n{self.db_file}",
            )
            if result == QMessageBox.No:
                return False

        gpkg_from_sql(db_file=self.db_file)
        QMessageBox.information(None, "Information", f"Created GeoPackage:\n\n{self.db_file}")
        return True


    def add_gpkg_layers_to_project(self) -> bool:
        """
        Add the GeoPackage layers to the current project.
        Returns a boolean indicating success of the process.
        """
        if not self.validate_qgis_state(project_active=True, db_file_exists=True):
            return False

        # Get layers root
        root = QgsProject.instance().layerTreeRoot()
        # Get db layers
        db_root_layer = QgsVectorLayer(str(self.db_file), "", "ogr")
        db_layers = db_root_layer.dataProvider().subLayers()
        db_layer_names = [
            layer.split(QgsDataProvider.SUBLAYER_SEPARATOR)[1]
            for layer in db_layers
        ]

        vector_layers = []
        for group_name, group_layer_names in self.layer_tree_structure.items():
            # Create the group if required
            add_to_legend = True
            if group_name is not None:
                group = root.addGroup(group_name)
                add_to_legend = False

            for layer_name in group_layer_names:
                # If the layer name in the dictionary is in the list of layers in the db file
                if layer_name in db_layer_names:

                    # Create layer
                    uri = f"{self.db_file}|layername={layer_name}"
                    vector_layer = QgsVectorLayer(uri, layer_name, "ogr")
                    QgsProject.instance().addMapLayer(vector_layer, add_to_legend)
                    vector_layers.append(vector_layer)

                    # Add layer to a group if required
                    if group_name is not None:
                        group.addLayer(vector_layer)

                    if layer_name.startswith("dic"):
                        vector_layer.setReadOnly()

        # We apply relationships and then styles after all layers are added to avoid conflicts
        self.find_create_relationships(vector_layers)
        self.apply_qml_styles(vector_layers)
        for layer in vector_layers:
            self.refresh_relation_reference_widgets(layer)
        QMessageBox.warning(
            None, "Warning",
            "Now add a project OR test data to allow you to begin adding locality data.",
        )
        return True

    def refresh_relation_reference_widgets(self, layer: QgsVectorLayer) -> None:
        """
        Recreate the relation reference widgets ensuring that they use the
        layer id that corresponds to the current project relationships.
        """
        relation_manager = QgsProject.instance().relationManager()
        widgets = self.editor_widget_metadata(layer)

        for idx, field_name in enumerate(widgets):
            if widgets[field_name]["type"] == "RelationReference":
                logger.debug("Updating relation widget for %s.%s",
                             layer.name(), field_name)
                config = widgets[field_name]["config"]

                matching_relations = relation_manager.relationsByName(config['Relation'])
                if len(matching_relations) != 1:
                    msg = f"Relation name ({config['Relation']}) is not unique"
                    raise ValueError(msg)
                relation = matching_relations[0]

                config.update({'ReferencedLayerId': relation.referencedLayerId()})
                new_widget = QgsEditorWidgetSetup('RelationReference', config)
                layer.setEditorWidgetSetup(idx, new_widget)

    @staticmethod
    def editor_widget_metadata(layer: QgsVectorLayer) -> dict[str, dict[str, Any]]:
        widgets = {}

        for field in layer.fields():
            widget_setup = field.editorWidgetSetup()
            widgets[field.name()] = {
                'type': widget_setup.type(),
                'config': widget_setup.config()
            }

        return widgets

    def log_active_layer_widgets(self) -> None:
        layer = self.iface.activeLayer()
        logger.debug("Layer ID: %s", layer.id())

        for field in layer.fields():
            widget_setup = field.editorWidgetSetup()
            if widget_setup.isNull():
                logger.debug("No editor widget for field '%s'", field.name())
            else:
                widget = {
                    'field': field.name(),
                    'widget_type': widget_setup.type(),
                    'widget_config': widget_setup.config()
                }
                logger.debug('\n' + pprint.pformat(widget, indent=2, sort_dicts=False))

            if widget_setup.type() == "RelationReference":
                relation_manager = QgsProject.instance().relationManager()
                # Check for duplicate relations
                matching_relations = relation_manager.relationsByName(widget_setup.config()['Relation'])
                logger.debug('Matching relations: %s', matching_relations)

                try:
                    relation = matching_relations[0]
                    relation_metadata = {
                        'name': relation.name(),
                        'isValid': relation.isValid(),
                        'referencingLayer': relation.referencingLayer(),
                        'referencingLayerId': relation.referencingLayerId(),
                        'referencedLayer': relation.referencedLayer(),
                        'referencedLayerId': relation.referencedLayerId(),
                    }
                    msg = pprint.pformat(relation_metadata, indent=2, sort_dicts=False)
                    logger.debug('Relation metadata:\n%s', msg)
                except IndexError:
                    logger.debug('No relations defined in project')

    @property
    def layer_tree_structure(self) -> dict[Optional[str], list[str]]:
        """
        Dictionary of layer names which will represent the QGIS layer tree structure.
        """
        # Create inital structure
        layer_tree_structure = {
            None: FEATURE_TABLES.difference(FEATURE_TABLES_LINES),
            "lines": FEATURE_TABLES_LINES,
            "views": VIEWS,
            "locality_data": ATTRIBUTE_TABLES,
            "metadata": DICTIONARIES,
        }

        # Sort the lists
        for group_name, table_set in layer_tree_structure.items():
            table_list = list(table_set)
            table_list.sort()
            layer_tree_structure[group_name] = table_list

        # Move the project layer
        project_name = "field_project"
        layer_tree_structure["locality_data"].remove(project_name)
        layer_tree_structure["metadata"].insert(0, project_name)

        # Move the view_next_locality_id
        next_id_name = "view_next_locality_id"
        layer_tree_structure["views"].remove(next_id_name)
        layer_tree_structure["metadata"].append(next_id_name)

        return layer_tree_structure


    def apply_qml_styles(self, vector_layers: list[QgsVectorLayer]) -> None:
        """
        Find and apply the QML style files for the given layers.
        """
        vector_layer_names = {
            vector_layer.name(): vector_layer
            for vector_layer in vector_layers
        }
        self.copy_plugin_files_to_project(plugin_src="styles", project_dest="styles")

        for qml_file in self.styles_dir.glob("*"):
            if qml_file.stem in vector_layer_names:
                # Apply the new style
                vector_layer_names[qml_file.stem].loadNamedStyle(str(qml_file))
                vector_layer_names[qml_file.stem].triggerRepaint()


    def find_create_relationships(self, vector_layers: list[QgsVectorLayer]) -> None:
        """
        Automatically find and create relationships between vector layers.
        """
        relation_manager = QgsProject.instance().relationManager()
        relations = relation_manager.discoverRelations([], vector_layers)
        for relation in relations:
            relation_manager.addRelation(relation)


    def open_layer_form(self, layer_name: str) -> bool:
        """
        Open the attribute form for the given layer.
        Returns a boolean indicating success of the process.
        """
        if not self.validate_qgis_state(project_active=True, db_file_exists=True, layer_name_exists=layer_name):
            return False

        layer = QgsProject.instance().mapLayersByName(layer_name)[0]

        # Ensure the layer is editable
        if not layer.isEditable():
            layer.startEditing()

        # Create a new feature with automatically generated values from the layer
        feature = QgsVectorLayerUtils.createFeature(layer)
        # We have to add the new feature to the layer before it can be opened in the form
        layer.addFeature(feature)
        keep_feature = self.iface.openFeatureForm(layer, feature)

        # Only save if the user confirms the new feature
        if keep_feature:
            layer.commitChanges()
            return True
        else:
            layer.rollBack()
            return False


    def add_test_data_to_project(self) -> bool:
        """
        Add the test data set to the current project.
        Returns a boolean indicating success of the process.
        """
        if not self.validate_qgis_state(project_active=True, db_file_exists=True):
            return False

        with sqlite3.connect(self.db_file) as conn:
            conn.enable_load_extension(True)
            add_test_data(conn)

        # Copy test data media files across into current project
        self.copy_plugin_files_to_project(plugin_src="test/data/photos", project_dest="photos")
        self.repaint_fdc_layers()
        QMessageBox.information(None, "Information", f"Added test data set to:\n\n{self.db_file}")
        return True


    def repaint_fdc_layers(self) -> None:
        """
        Trigger a repaint for only the layers which come from the Field Data Capture plugin.
        """
        for layer in QgsProject.instance().mapLayers().values():
            if layer.name() in set(TABLE_LIST):
                layer.triggerRepaint()


    def copy_plugin_files_to_project(self, plugin_src: Path, project_dest: Path) -> None:
        """
        Copy the files from the given plugin source directory into the given project destination directory.
        """
        plugin_src_dir = WORKDIR / plugin_src
        project_dest_dir = self.project_dir / project_dest
        project_dest_dir.mkdir(parents=True, exist_ok=True)

        for src_file in plugin_src_dir.glob("*"):
            dest_file = project_dest_dir / src_file.name
            dest_file.write_bytes(src_file.read_bytes())


    def export_qml_styles(self) -> bool:
        """
        Export the QML styles for layers which belong to the Field Data Capture project.
        These are saved into the current project's styles directory.
        Returns a boolean indicating success of the process.
        """
        if not self.validate_qgis_state(project_active=True, db_file_exists=True, fdc_layers_exist=True):
            return False

        # Compare the QGIS version in the existing styles to the current QGIS version
        # Get the first existing QML style and parse it's XML
        existing_xml_style = minidom.parse(str(list(self.styles_dir.glob("*.qml"))[0]))
        existing_version = existing_xml_style.getElementsByTagName("qgis")[0].attributes["version"].value
        current_version = Qgis.version()
        if existing_version != current_version:
            result = QMessageBox.question(
                None, "Conflicting QGIS Versions",
                (
                    f"The existing QML files are from QGIS '{existing_version}', "
                    f"but you are using QGIS '{current_version}'. "
                    "Continuing will cause bad style diffs.\n\nDo you want to continue?"
                ),
            )
            if result == QMessageBox.No:
                return False

        # Export the current styles
        exported_styles = 0
        for table_name in TABLE_LIST:
            layer_style_path = self.styles_dir / (table_name + ".qml")
            # If the layer exists and a style file has already been saved for it
            if self.check_layer_exists(table_name) and layer_style_path.exists():
                exported_styles += 1

                # Save the style of the current layer
                layer = QgsProject.instance().mapLayersByName(table_name)[0]
                layer.saveNamedStyle(
                    str(layer_style_path),
                    categories=QgsMapLayer.Symbology | QgsMapLayer.Labeling | QgsMapLayer.Fields | QgsMapLayer.Forms,
                )

                # Read the newly created XML file
                raw_xml = layer_style_path.read_text()
                # Canonicalize the XML data and save back to the same file
                # Set the newline manually to force LF line endings
                with open(layer_style_path, "w", newline="\n") as qml_file:
                    canonicalize(xml_data=raw_xml, out=qml_file)

        QMessageBox.information(
            None, "Information",
            f"{exported_styles} Field Data Capture styles have been exported to:\n\n{self.styles_dir}",
        )
        return True


    def toggle_quick_locality_point_mode(self) -> bool:
        """
        Toggle the mode used for creating quick locality points.
        """
        if not self.validate_qgis_state(project_active=True, db_file_exists=True, fdc_layers_exist=True):
            # Ensure the button is not left toggled
            if self.quick_locality_point_button.isChecked():
                self.quick_locality_point_button.toggle()
            return False

        layer = QgsProject.instance().mapLayersByName("locality_point")[0]

        if self.quick_locality_point_mode:
            self.disable_quick_locality_point(layer)

        else:
            self.enable_quick_locality_point(layer)


    def enable_quick_locality_point(
        self,
        layer: QgsVectorLayer,
        connect_slots: bool = True,
    ) -> bool:
        """
        Enable the quick locality point mode. This allows users to quickly add locality_point
        feature with minimal button clicks.
        Returns a boolean indicating success of the process.
        """
        # Ensure the layer is editable
        if not layer.isEditable():
            layer.startEditing()

        self.iface.setActiveLayer(layer)

        if connect_slots:
            self.connect_post_new_point_functions(layer)
            self.connect_close_project_function(layer)

        # Trigger the "Add Point Feature" button
        self.iface.actionAddFeature().trigger()

        self.quick_locality_point_mode = True

        return True


    def connect_post_new_point_functions(self, layer: QgsVectorLayer) -> None:
        """
        Create and connect the temporary slot functions for the quick locality point mode.
        The first slot will save the 'fid' of the new locality_point feature.
        The second slot will open the form for the new locality_point feature, and
        re-enable the quick locality point mode.
        """
        def store_quick_locality_point_fid(fid: int) -> None:
            """
            The featureAdded signal from a QgsVectorLayer triggers twice when a new feature is added through a form.
            This appears to be because the unsaved feature is added first to the layer in a temporary state, for viewing
            in the attribute table. This means that from the front end, it's 'fid' value is 'AutoGenerate', whilst
            from the back end, it's 'fid' is a negative integer.

            Once the layer changes are saved, this temporary new feature is removed, and
            the actual new feature with a real 'fid' value is added.
            However, this actual new feature then triggers the featureAdded signal again.

            Therefore, we only want to act on the signal when the 'fid' value is positive, as that will be
            the real new feature that we want.
            """
            if fid > 0:
                # Save the 'fid' of the new feature for use later
                self.quick_locality_point_fid = fid

        def commit_changes_and_reopen_form(*args) -> None:
            """
            The layer changes must be saved before we can get the new locality_point feature and open it's form.
            This is because before the changes are saved, the newest feature will be the temporary one,
            and we do not save that temporary 'fid' value.

            After the form has been opened, we re-enable the quick locality point mode without the slots.
            This is because the slots still exist from the button toggle when it was first enabled,
            and so we do not need to set them up again.
            """
            # Save the layer changes
            layer.commitChanges()

            # Only re-open the feature form if the editCommandEnded signal triggers due to a new point
            # If it is a new point, it's 'fid' will have been saved by the featureAdded signal
            if self.quick_locality_point_fid is not None:
                # Open the new feature's form
                new_feature = layer.getFeature(self.quick_locality_point_fid)
                self.iface.openFeatureForm(layer, new_feature)
            
            # Otherwise, the user has just completed an edit on an existing locality_point feature
            else:
                self.warn_unsaved_locality_children()

            # Re-enable the quick locality point mode
            self.enable_quick_locality_point(layer, connect_slots=False)
            # Remove the saved 'fid' so that we know we have dealt with the new point
            self.quick_locality_point_fid = None

        # Connect the signals and slots
        layer.featureAdded.connect(store_quick_locality_point_fid)
        layer.editCommandEnded.connect(commit_changes_and_reopen_form)

        # Save the slot functions so we can disconnect them later
        self.locality_point_slots.append((layer.featureAdded, store_quick_locality_point_fid))
        self.locality_point_slots.append((layer.editCommandEnded, commit_changes_and_reopen_form))


    def connect_close_project_function(self, layer: QgsVectorLayer) -> None:
        """
        Create and connect a slot function which will be run when the current QGIS project is about to be closed.
        This is a new signal as of QGIS 3.34, previously we would have to use QgsProject.cleared.
        This allows us to disable the quick locality point mode in the background without causing issues.
        """
        qgs_project = QgsProject.instance()

        def disable_on_close() -> None:
            self.disable_quick_locality_point(layer)
            # The function then disconnects itself from the slot to ensure nothing about QGIS is left modified
            qgs_project.aboutToBeCleared.disconnect(disable_on_close)

        qgs_project.aboutToBeCleared.connect(disable_on_close)


    def disable_quick_locality_point(
        self,
        layer: QgsVectorLayer,
    ) -> None:
        """
        Disable the quick locality point mode and remove any temporary slots.
        """
        # Stop editing the layer
        # New points are automatically saved, so this should not remove any changes
        if layer.isEditable():
            layer.rollBack()

        # Disconnect the slots
        for signal, slot_function in self.locality_point_slots:
            signal.disconnect(slot_function)
        self.locality_point_slots = []

        # Disable quick locality point mode
        self.quick_locality_point_mode = False
        self.quick_locality_point_fid = None
        if self.quick_locality_point_button.isChecked():
            self.quick_locality_point_button.toggle()

        self.warn_unsaved_locality_children()


    def warn_unsaved_locality_children(self) -> None:
        """
        Check if any of the locality_point child layers have unsaved changes.
        If they do, a warning message is shown to the user in the form of a QMessageBox.
        """
        unsaved_layers = []
        for layer_name in LOCALITY_POINT_CHILDREN:
            layer = QgsProject.instance().mapLayersByName(layer_name)[0]
            if layer.isModified():
                unsaved_layers.append(layer_name)

        if unsaved_layers:
            # Create the list of unsaved layer names to display in the QMessageBox
            joined_names = "\n".join(unsaved_layers)
            # Manually build the QMessageBox so we can change the icon
            message_box = QMessageBox()
            message_box.setWindowTitle("Warning")
            message_box.setText(f"There are unsaved edits on the following layer(s):\n\n{joined_names}")
            message_box.setStandardButtons(QMessageBox.Ok)
            # Get the 'Current Edits' red pencils icon as a pixmap the size of the default QMessageBox icons
            red_pencils_pixmap = self.iface.actionAllEdits().icon().pixmap(48, 48)
            # Set the icon using the pixmap
            message_box.setIconPixmap(red_pencils_pixmap)
            # Open the message box
            message_box.exec_()
