    @staticmethod
    def project_is_active() -> bool:
        """
        Check if a saved project is currently open.
        """
        if QgsProject.instance().fileName() != '':
            return True
        else:
            QMessageBox.information(None, "Information", "Please open a saved project.")
            return False


    @staticmethod
    def check_layer_exists(layer_name: str) -> bool:
        """
        Check if a given layer name exists in the list of current layers.
        """
        if len(QgsProject.instance().mapLayersByName(layer_name)) > 0:
            return True
        else:
            return False


    @staticmethod
    def check_fdc_layers_exist() -> bool:
        """
        Check if the Field Data Capture layers exist in the current layers.
        """
        missing_layers = [
            table_name
            for table_name in TABLE_LIST
            if not FieldDataCapture.check_layer_exists(table_name)
        ]
        if len(missing_layers) == 0:
            return True
        else:
            return False


    def run_function_list(self, functions: list[Callable]) -> bool:
        """
        Run all the given functions in order.
        Each function must return a boolean indicating it's success.
        If a function returns False, function execution will end.
        Returns a boolean indicating success of the process.
        """
        for function_ in functions:
            return_ = function_()
            # We don't want to continue through the setup if a process fails
            if return_ is False:
                return False

        return True


    def add_gpkg_to_project(self) -> bool:
        """
        Add the GeoPackage file to the current project.
        Returns a boolean indicating success of the process.
        """
        # Check that we have an open project
        if not self.project_is_active():
            return False

        if self.db_file.exists():
            result = QMessageBox.question(
                None, "File Already Exists",
                f"The file already exists, would you like to overwrite the file?\n\n{self.db_file}",
            )
            if result == QMessageBox.No:
                return False

        gpkg_from_sql(db_file=self.db_file)
        QMessageBox.information(None, "Information", f"Created GeoPackage:\n\n{self.db_file}")
        return True


    def add_gpkg_layers_to_project(self) -> bool:
        """
        Add the GeoPackage layers to the current project.
        Returns a boolean indicating success of the process.
        """
        # Check that we have an open project and a geopackage
        if not self.project_is_active():
            return False
        if not self.db_file.exists():
            QMessageBox.information(None, "Information", f"Could not find file:\n\n{self.db_file}")
            return False

        # Get layers root
        root = QgsProject.instance().layerTreeRoot()
        # Get db layers
        db_root_layer = QgsVectorLayer(str(self.db_file), "", "ogr")
        db_layers = db_root_layer.dataProvider().subLayers()
        db_layer_names = [
            layer.split(QgsDataProvider.SUBLAYER_SEPARATOR)[1]
            for layer in db_layers
        ]

        vector_layers = []
        for group_name, group_layer_names in self.layer_tree_structure.items():
            # Create the group if required
            add_to_legend = True
            if group_name is not None:
                group = root.addGroup(group_name)
                add_to_legend = False

            for layer_name in group_layer_names:
                # If the layer name in the dictionary is in the list of layers in the db file
                if layer_name in db_layer_names:

                    # Create layer
                    uri = f"{self.db_file}|layername={layer_name}"
                    vector_layer = QgsVectorLayer(uri, layer_name, "ogr")
                    QgsProject.instance().addMapLayer(vector_layer, add_to_legend)
                    vector_layers.append(vector_layer)

                    # Add layer to a group if required
                    if group_name is not None:
                        group.addLayer(vector_layer)

                    if layer_name.startswith("dic"):
                        vector_layer.setReadOnly()

        # We apply relationships and then styles after all layers are added to avoid conflicts
        self.find_create_relationships(vector_layers)
        self.apply_qml_styles(vector_layers)
        for layer in vector_layers:
            self.refresh_relation_reference_widgets(layer)
        QMessageBox.warning(
            None, "Warning",
            "Now add a project OR test data to allow you to begin adding locality data.",
        )
        return True

    def refresh_relation_reference_widgets(self, layer: QgsVectorLayer) -> None:
        """
        Recreate the relation reference widgets ensuring that they use the
        layer id that corresponds to the current project relationships.
        """
        relation_manager = QgsProject.instance().relationManager()
        widgets = self.editor_widget_metadata(layer)

        for idx, field_name in enumerate(widgets):
            if widgets[field_name]["type"] == "RelationReference":
                logger.debug("Updating relation widget for %s.%s",
                             layer.name(), field_name)
                config = widgets[field_name]["config"]

                matching_relations = relation_manager.relationsByName(config['Relation'])
                if len(matching_relations) != 1:
                    msg = f"Relation name ({config['Relation']}) is not unique"
                    raise ValueError(msg)
                relation = matching_relations[0]

                config.update({'ReferencedLayerId': relation.referencedLayerId()})
                new_widget = QgsEditorWidgetSetup('RelationReference', config)
                layer.setEditorWidgetSetup(idx, new_widget)

    @staticmethod
    def editor_widget_metadata(layer: QgsVectorLayer) -> dict[str, dict[str, Any]]:
        widgets = {}

        for field in layer.fields():
            widget_setup = field.editorWidgetSetup()
            widgets[field.name()] = {
                'type': widget_setup.type(),
                'config': widget_setup.config()
            }

        return widgets

    def log_active_layer_widgets(self) -> None:
        layer = self.iface.activeLayer()
        logger.debug("Layer ID: %s", layer.id())

        for field in layer.fields():
            widget_setup = field.editorWidgetSetup()
            if widget_setup.isNull():
                logger.debug("No editor widget for field '%s'", field.name())
            else:
                widget = {
                    'field': field.name(),
                    'widget_type': widget_setup.type(),
                    'widget_config': widget_setup.config()
                }
                logger.debug('\n' + pprint.pformat(widget, indent=2, sort_dicts=False))

            if widget_setup.type() == "RelationReference":
                relation_manager = QgsProject.instance().relationManager()
                # Check for duplicate relations
                matching_relations = relation_manager.relationsByName(widget_setup.config()['Relation'])
                logger.debug('Matching relations: %s', matching_relations)

                try:
                    relation = matching_relations[0]
                    relation_metadata = {
                        'name': relation.name(),
                        'isValid': relation.isValid(),
                        'referencingLayer': relation.referencingLayer(),
                        'referencingLayerId': relation.referencingLayerId(),
                        'referencedLayer': relation.referencedLayer(),
                        'referencedLayerId': relation.referencedLayerId(),
                    }
                    msg = pprint.pformat(relation_metadata, indent=2, sort_dicts=False)
                    logger.debug('Relation metadata:\n%s', msg)
                except IndexError:
                    logger.debug('No relations defined in project')

    @property
    def layer_tree_structure(self) -> dict[Optional[str], list[str]]:
        """
        Dictionary of layer names which will represent the QGIS layer tree structure.
        """
        # Create inital structure
        layer_tree_structure = {
            None: FEATURE_TABLES.difference(FEATURE_TABLES_LINES),
            "lines": FEATURE_TABLES_LINES,
            "views": VIEWS,
            "locality_data": ATTRIBUTE_TABLES,
            "metadata": DICTIONARIES,
        }

        # Sort the lists
        for group_name, table_set in layer_tree_structure.items():
            table_list = list(table_set)
            table_list.sort()
            layer_tree_structure[group_name] = table_list

        # Move the project layer
        project_name = "field_project"
        layer_tree_structure["locality_data"].remove(project_name)
        layer_tree_structure["metadata"].insert(0, project_name)

        # Move the view_next_locality_id
        next_id_name = "view_next_locality_id"
        layer_tree_structure["views"].remove(next_id_name)
        layer_tree_structure["metadata"].append(next_id_name)

        return layer_tree_structure


    def apply_qml_styles(self, vector_layers: list[QgsVectorLayer]) -> None:
        """
        Find and apply the QML style files for the given layers.
        """
        vector_layer_names = {
            vector_layer.name(): vector_layer
            for vector_layer in vector_layers
        }
        self.copy_plugin_files_to_project(plugin_src="styles", project_dest="styles")

        for qml_file in self.styles_dir.glob("*"):
            if qml_file.stem in vector_layer_names:
                # Apply the new style
                vector_layer_names[qml_file.stem].loadNamedStyle(str(qml_file))
                vector_layer_names[qml_file.stem].triggerRepaint()


    def find_create_relationships(self, vector_layers: list[QgsVectorLayer]) -> None:
        """
        Automatically find and create relationships between vector layers.
        """
        relation_manager = QgsProject.instance().relationManager()
        relations = relation_manager.discoverRelations([], vector_layers)
        for relation in relations:
            relation_manager.addRelation(relation)


    def open_layer_form(self, layer_name: str) -> bool:
        """
        Open the attribute form for the given layer.
        Returns a boolean indicating success of the process.
        """
        if not self.project_is_active():
            return False
        if not self.db_file.exists():
            QMessageBox.information(None, "Information", f"Could not find file:\n\n{self.db_file}")
            return False
        if not self.check_layer_exists(layer_name):
            QMessageBox.information(None, "Information", f"Could not find layer: {layer_name}")
            return False
        layer = QgsProject.instance().mapLayersByName(layer_name)[0]

        # Ensure the layer is editable
        if not layer.isEditable():
            layer.startEditing()

        # Create a new feature with automatically generated values from the layer
        feature = QgsVectorLayerUtils.createFeature(layer)
        # We have to add the new feature to the layer before it can be opened in the form
        layer.addFeature(feature)
        keep_feature = self.iface.openFeatureForm(layer, feature)

        # Only save if the user confirms the new feature
        if keep_feature:
            layer.commitChanges()
            return True
        else:
            layer.rollBack()
            return False


